export function tr(text, lang = "English") {
  if (!text) return "";
  const l = (lang === "Telugu" || lang === "తెలుగు") ? "తెలుగు"
          : (lang === "Hindi" || lang === "हिन्दी") ? "हिन्दी"
          : (lang === "Kannada" || lang === "ಕನ್ನಡ") ? "ಕನ್ನಡ"
          : "English";
  if (l === "English") return text;
  
  const clean = String(text).trim();
  if (translationsMap[l] && translationsMap[l][clean]) {
    return translationsMap[l][clean];
  }
  return text;
}


export function getTranslation(lang, key) {
  const dict = translations[lang] || translations.English;
  if (dict[key]) return dict[key];
  if (translations.English[key]) return translations.English[key];
  return tr(key, lang);
}

